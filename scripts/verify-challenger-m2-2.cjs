function renderTransactionHistory({ language, search = "", sample = false }) {
  const state = createTestState(language);
  const mockStore = {
    useAppState: () => state,
    today: () => "2026-10-12",
    money: (v) => String(v),
    currencySymbol: () => "₫",
  };

  const customHistory = compileFile(path.join(replicaDir, "TransactionHistory.tsx"), (name) => {
    if (name === "./store") return mockStore;
    if (name === "./FinBridgeHeader") return headerModule;
    if (name === "./Dashboard") return dashboardModule;
    if (name === "./CalendarLedgerModal") return { CalendarLedgerModal: () => null };
    if (name === "next/navigation") {
      return {
        useRouter: () => ({ push: () => {}, replace: () => {}, refresh: () => {} }),
        useSearchParams: () => new URLSearchParams(sample ? { source: "sample" } : {}),
      };
    }
    return undefined;
  }, new Map());

  return renderToStaticMarkup(
    React.createElement(customHistory.TransactionHistory, {
      navigate: () => {},
      defaultSearch: search,
    })
  );
}

