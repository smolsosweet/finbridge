export function appUiText(text: string, language: unknown): string {
  const lang = resolveLanguage(language, "en");
  const source = text.trim();
  const entry = APP_UI_COPY[source] ? [source, APP_UI_COPY[source]] as const : Object.entries(APP_UI_COPY).find(([, values]) => values.includes(source));
  if (!entry) return text;
  const translated = lang === "vi" ? entry[0] : entry[1][lang === "zh" ? 1 : 0];
  return text.replace(source, translated);
}
