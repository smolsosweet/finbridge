import { readMailConfig } from "./auth-mail";

export function safetyEmailAvailable(env: NodeJS.ProcessEnv = process.env) {
  try {
    return (
      env.SAFETY_EMAIL_ENABLED === "true" &&
      (env.SAFETY_CRON_SECRET?.length || 0) >= 32 &&
      readMailConfig(env)?.mode === "brevo"
    );
  } catch {
    return false;
  }
}

